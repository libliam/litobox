/**
 * 从 README.md 的版本路线表生成 changelog 数据
 * 用法: node scripts/gen-changelog.cjs
 * 输出: src/utils/changelogData.ts
 *
 * 设计原则：用户只关心每个版本新增/优化了什么功能，不关心 git 提交细节
 * 数据源：README.md 的版本路线表，内容经过人工整理，是面向用户的描述
 */
const fs = require('fs');
const path = require('path');

// 判断描述是否偏向「功能增强/优化/修复」类
function isEnhancement(desc) {
  const s = desc.toLowerCase();
  return (
    /修复|修复|改进|增强|优化|重构|调整|兼容|兼容|升级|规范|统一|整合|简化|完善/.test(desc) ||
    /工具增强|工具扩展|修复|问题/.test(s)
  );
}

// 判断描述是否偏向「新增」类（新工具 / 新功能模块）
function isNewFeature(desc) {
  return (
    /新增|新工具|新增工具|查看器|编辑器|管理器|生成器|面板|工具集/.test(desc) ||
    /：(查看|管理|编辑|生成|分析|识别|裁剪|压缩|提取|转换|启动|搜索|导出|导入|存储|索引|美化|探测|清理|释放)/.test(desc)
  );
}

function main() {
  const readmePath = path.resolve(__dirname, '..', 'README.md');
  const readme = fs.readFileSync(readmePath, 'utf8');

  const versions = [];
  // 匹配"版本路线"章节到下一个二级标题之前
  const tableMatch = readme.match(/## 🗺️ 版本路线[\s\S]*?(?=\n## )/);
  if (tableMatch) {
    // 逐行处理版本表：| Vx.y.z | ✅ | 描述 | 日期(可选) |
    const lines = tableMatch[0].split('\n');
    for (const rawLine of lines) {
      const line = rawLine.trim();
      if (!line.startsWith('|')) continue;
      const cells = line.split('|').map(c => c.trim());
      // cells[0] 和 cells[cells.length-1] 是边界空串
      // 正常行: ['', 'V7.2.0', '✅', '内容...', '2026-08-09', '']  或 没有日期的 5 格
      if (cells.length < 5) continue;
      const version = cells[1].replace(/^[Vv]/, '');
      if (!/^\d/.test(version)) continue;
      const content = cells[3];
      if (!content) continue;
      const date = cells.length >= 6 ? (cells[4] || '').trim() : '';
      versions.push({
        version,
        date,
        content,
        isEnhancement: isEnhancement(content),
        isNewFeature: isNewFeature(content)
      });
    }
  }

  // 降序排序（版本号比较）
  const vNum = (v) => {
    const parts = v.replace(/x/g, '0').split('.').map(n => parseInt(n) || 0);
    while (parts.length < 3) parts.push(0);
    return parts[0] * 1000000 + parts[1] * 1000 + parts[2];
  };
  versions.sort((a, b) => vNum(b.version) - vNum(a.version));

  // 计算版本范围字符串
  let versionRange = '';
  const stable = versions.filter(v => !v.version.includes('x'));
  if (stable.length >= 2) {
    const oldest = stable[stable.length - 1].version;
    const newest = stable[0].version;
    versionRange = `从 v${oldest} 到 v${newest} 更新内容`;
  } else if (stable.length === 1) {
    versionRange = `v${stable[0].version} 更新内容`;
  }

  const tsContent = `// Auto-generated by scripts/gen-changelog.cjs
// 请勿手动修改此文件，如需更新请运行: node scripts/gen-changelog.cjs

export interface ChangelogEntry {
  version: string
  date: string
  content: string
  isEnhancement: boolean
  isNewFeature: boolean
}

export interface ChangelogData {
  versionRange: string
  entries: ChangelogEntry[]
}

export const changelogData: ChangelogData = {
  versionRange: ${JSON.stringify(versionRange)},
  entries: ${JSON.stringify(versions, null, 2)}
}
`;

  const outPath = path.resolve(__dirname, '..', 'src', 'utils', 'changelogData.ts');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, tsContent, 'utf8');

  console.log(`✅ 已生成 changelog 数据: ${outPath}`);
  console.log(`   版本数: ${versions.length}`);
  console.log(`   范围: ${versionRange}`);
  const newCount = versions.filter(v => v.isNewFeature && !v.isEnhancement).length;
  const enhCount = versions.filter(v => v.isEnhancement).length;
  const mixedCount = versions.filter(v => v.isNewFeature && v.isEnhancement).length;
  console.log(`   新增类 ${newCount} 条 · 增强类 ${enhCount} 条 · 混合类 ${mixedCount} 条`);
}

main();
